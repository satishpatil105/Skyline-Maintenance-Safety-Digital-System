async function seedDetailedChecklists() {
  const uri = getUri();
  const client = new MongoClient(uri);
  try {
    await client.connect();
    const db = client.db("Skyline_Project_Engineers");

    console.log(`Clearing existing records and inserting ${DETAILED_CHECKLISTS.length} highly-detailed machine-wise checklist points...`);

    // Clean existing
    await db.collection("checklist_master").deleteMany({});

    // Prepare documents with metadata
    const docs = DETAILED_CHECKLISTS.map((item, index) => ({
      ...item,
      "Template ID": `CHK-DET-${String(index + 1).padStart(3, "0")}`,
      "Asset ID / Machine": item["Asset ID"],
      "Check Point / Task": item["Check Point"],
      "Standard Parameter": item["Standard Requirement"],
      Status: item.Active === "Yes" ? "Active" : "Inactive",
      "Created Date": new Date().toISOString().split("T")[0],
      createdAt: new Date().toISOString(),
    }));

    const result = await db.collection("checklist_master").insertMany(docs);
    console.log(`✓ Successfully inserted ${result.insertedCount} detailed checklist points into MongoDB Atlas!`);

    // Summary of covered machines
    const machineSet = new Set(DETAILED_CHECKLISTS.map((c) => c["Asset ID"]));
    console.log("\nCovered Machines in Detailed Checklist Master:");
    machineSet.forEach((m) => console.log(`  - ${m}`));

    console.log("\n=== DETAILED CHECKLIST SEEDING COMPLETED SUCCESSFULLY ===");
  } finally {
    await client.close();
  }
}

seedDetailedChecklists().catch(console.error);
